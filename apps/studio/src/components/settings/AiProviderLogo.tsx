/** Soft brand plate behind a provider mark. */
export function AiProviderLogoBadge({
  provider,
  size = "md",
  className = "",
}: {
  provider: AiProvider;
  size?: "sm" | "md" | "lg";
  className?: string;
}) {
  const box =
    size === "lg"
      ? "w-14 h-14 rounded-[var(--radius-lg)]"
      : size === "sm"
        ? "w-8 h-8 rounded-[var(--radius-md)]"
        : "w-11 h-11 rounded-[var(--radius-md)]";
  const icon = size === "lg" ? "w-7 h-7" : size === "sm" ? "w-4 h-4" : "w-5 h-5";

  const tint: Record<AiProvider, string> = {
    openai: "bg-emerald-500/15 text-emerald-700 dark:text-emerald-300",
    anthropic: "bg-amber-500/15 text-orange-800 dark:text-orange-300",
    google: "bg-sky-500/10 text-sky-700 dark:text-sky-300",
    deepseek: "bg-violet-500/15 text-violet-700 dark:text-violet-300",
    openai_compatible: "bg-stone-500/15 text-stone-700 dark:text-stone-300",
  };

  return (
    <span
      className={`${box} ${tint[provider]} flex items-center justify-center shrink-0 ${className}`}
    >
      <AiProviderLogo provider={provider} className={icon} />
    </span>
  );
}
